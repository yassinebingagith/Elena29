import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(projectRoot, "game/fighter-assets.js");

const assets = [
  {
    key: "elena-fighter",
    file: "assets/game/characters/processed/elena-poses.png",
    frameWidth: 418,
    frameHeight: 627
  },
  {
    key: "yanina-fighter",
    file: "assets/game/characters/processed/yanina-poses.png",
    frameWidth: 512,
    frameHeight: 512
  }
];

const embeddedAssets = await Promise.all(assets.map(async (asset) => ({
  key: asset.key,
  src: `data:image/png;base64,${(await readFile(resolve(projectRoot, asset.file))).toString("base64")}`,
  frameWidth: asset.frameWidth,
  frameHeight: asset.frameHeight
})));

const output = `// Generated by scripts/build-fighter-assets.mjs.\nwindow.AURORA_FIGHTER_ASSETS = Object.freeze(${JSON.stringify(embeddedAssets)});\n`;
await writeFile(outputPath, output, "utf8");

